// Regenerate THIRD_PARTY_NOTICES.md from Cargo.lock (through `cargo metadata`) and the UI package lock.
//
//   node scripts/release/third-party-notices.mjs          write the file
//   node scripts/release/third-party-notices.mjs --check  fail if the file is out of date
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "../..");
const output = resolve(repositoryRoot, "THIRD_PARTY_NOTICES.md");

function cell(value) {
  return String(value ?? "unknown").replaceAll("|", "\\|");
}

function rustPackages() {
  const metadata = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: repositoryRoot,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    }),
  );
  return metadata.packages
    .filter((item) => item.source !== null)
    .map((item) => ({ name: item.name, version: item.version, license: item.license }));
}

async function uiPackages() {
  const lock = JSON.parse(
    await readFile(resolve(repositoryRoot, "apps/desktop/package-lock.json"), "utf8"),
  );
  return Object.entries(lock.packages)
    .filter(([path, item]) => path.startsWith("node_modules/") && !item.dev)
    .map(([path, item]) => ({
      name: path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: item.version,
      license: item.license,
    }));
}

function table(packages) {
  const unique = new Map();
  for (const item of packages) unique.set(`${item.name}@${item.version}`, item);
  const rows = [...unique.values()]
    .sort((left, right) => left.name.localeCompare(right.name) || left.version.localeCompare(right.version))
    .map((item) => `| ${cell(item.name)} | ${cell(item.version)} | ${cell(item.license)} |`);
  return ["| Package | Version | License |", "| --- | --- | --- |", ...rows].join("\n");
}

const engineLock = JSON.parse(await readFile(resolve(repositoryRoot, "engines.lock.json"), "utf8"));
const engineVersion = engineLock.engine.version;

const text = `# Third-party notices

<!-- Generated by scripts/release/third-party-notices.mjs. Do not edit by hand. -->

TunBridge is licensed under GPL-3.0-or-later. Its packages include the components below, each under its own
license. License texts are available from each project's source distribution.

## Bundled engine

| Component | Version | License | Source |
| --- | --- | --- | --- |
| [Mihomo](https://github.com/MetaCubeX/mihomo) | ${engineVersion} | GPL-3.0 | https://github.com/MetaCubeX/mihomo/tree/${engineVersion} |

Every TunBridge package ships an unmodified Mihomo release binary. The corresponding source code is the
Mihomo tag listed above; each TunBridge release also links it in its release notes.

The Windows Mihomo binary embeds the [Wintun](https://www.wintun.net/) driver, Copyright WireGuard LLC,
which is redistributed unmodified, as part of Mihomo, under the Wintun prebuilt binaries license.

## Rust crates

Dependencies resolved in \`Cargo.lock\` for all supported platforms, including build-time dependencies.

${table(rustPackages())}

## UI packages

Runtime packages bundled into the desktop UI (\`apps/desktop/package-lock.json\`, development-only packages
excluded).

${table(await uiPackages())}
`;

if (process.argv.includes("--check")) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== text) {
    console.error("THIRD_PARTY_NOTICES.md is out of date; run node scripts/release/third-party-notices.mjs");
    process.exit(1);
  }
  console.log("third_party_notices=ok");
} else {
  await writeFile(output, text);
  console.log(`wrote ${output}`);
}
