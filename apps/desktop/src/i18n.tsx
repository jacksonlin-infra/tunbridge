export const translate = (language: Language, text: string): string =>
  language === "en" ? text : (v2Catalog[text] ?? catalog[text])?.[language] ?? text;

/** Fills `{name}` placeholders after translating the template. */
export const translateFormat = (
  language: Language,
  template: string,
  values: Record<string, string | number>,
): string =>
  translate(language, template).replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match);

export const hasTranslation = (text: string): boolean =>
  Object.hasOwn(v2Catalog, text) || Object.hasOwn(catalog, text);

type I18nValue = {
  language: Language;
  t: (text: string) => string;
  tf: (template: string, values: Record<string, string | number>) => string;
};

const contextValue = (language: Language): I18nValue => ({
  language,
  t: (text) => translate(language, text),
  tf: (template, values) => translateFormat(language, template, values),
});

const I18nContext = createContext<I18nValue>(contextValue("zh-CN"));

export function I18nProvider({ language, children }: { language: Language; children: ReactNode }) {
  return (
    <I18nContext.Provider value={contextValue(language)}>
      {children}
    </I18nContext.Provider>
  );
}

export const useI18n = () => useContext(I18nContext);
